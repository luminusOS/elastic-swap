#!/usr/bin/env bash
# Build the RPM and its source tarballs under dist/ from the files git tracks
# or would track (untracked files that .gitignore excludes stay out).
# Run inside an environment with rpm-build, cargo and rust installed.
set -euo pipefail

cd "$(dirname "$0")/.."
version=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n 1)
name=elastic-swap
top=$PWD/dist/rpmbuild

rm -rf "$top"
mkdir -p "$top"/{SOURCES,SPECS,BUILD,RPMS,SRPMS}

stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT
src=$stage/$name-$version
mkdir "$src"
git ls-files -z --cached --others --exclude-standard \
    | tar --null -T - -c \
    | tar -x -C "$src"

(cd "$src" && cargo vendor --locked vendor >/dev/null)

# Notices for the statically linked crates: MIT and BSD-3-Clause require them to
# travel with the binary. Vendored crates that the Linux build does not link are
# included too, which errs on the side of too much.
{
    echo "Licence notices of the Rust crates built into elastic-swap $version."
    echo "Generated by packaging/build-rpm.sh from the vendored sources."
    for dir in "$src"/vendor/*/; do
        crate=$(basename "$dir")
        for file in "$dir"LICENSE* "$dir"COPYING* "$dir"UNLICENSE* "$dir"NOTICE*; do
            [ -f "$file" ] || continue
            printf '\n==== %s: %s ====\n\n' "$crate" "$(basename "$file")"
            cat "$file"
        done
    done
} >"$src/LICENSE.dependencies"

tar -C "$stage" -czf "$top/SOURCES/$name-$version.tar.gz" --exclude="$name-$version/vendor" "$name-$version"
tar -C "$src" -cJf "$top/SOURCES/$name-$version-vendor.tar.xz" vendor

cp packaging/$name.spec "$top/SPECS/"
rpmbuild --define "_topdir $top" -ba "$top/SPECS/$name.spec"

mkdir -p dist
find "$top/RPMS" "$top/SRPMS" -name '*.rpm' -exec cp -v {} dist/ \;
cp "$top"/SOURCES/*.tar.* dist/
(cd dist && sha256sum ./*.rpm ./*.tar.* | tee SHA256SUMS)
echo "Publish dist/*.src.rpm and the tarballs with the binary RPM (GPLv3 section 6)."
